-- PostgreSQL(RDS)와 H2(PostgreSQL 모드, 로컬/테스트) 양쪽에서 동작하는 표준 SQL만 사용

CREATE TABLE performance (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(200)             NOT NULL,
    venue      VARCHAR(200)             NOT NULL,
    starts_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    price      INTEGER                  NOT NULL
);

CREATE TABLE seat (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    performance_id BIGINT      NOT NULL REFERENCES performance (id),
    seat_no        VARCHAR(10) NOT NULL,
    status         VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    CONSTRAINT uk_seat_performance_seat_no UNIQUE (performance_id, seat_no)
);

CREATE TABLE reservation (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(16)              NOT NULL,
    seat_id       BIGINT                   NOT NULL REFERENCES seat (id),
    customer_name VARCHAR(50)              NOT NULL,
    status        VARCHAR(20)              NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    cancelled_at  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_reservation_code UNIQUE (code)
);

CREATE INDEX idx_reservation_seat ON reservation (seat_id);
